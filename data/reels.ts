/* ---------------------------------------------------------------------------
   The reel corpus.

   `feed` reels are the sample inputs from the brief — what a student is already
   scrolling, spanning entertainment, gaming, coding, AI, gadgets, career,
   programming memes and tech news. `catalog` reels are what Upstream can serve
   back: real technical content with a stated outcome and an honest difficulty.

   Two fields carry the guardrails:
   • `substance` (0–1) — how much transferable content survives the 45 seconds.
   • `hypeMarkers` — the exact phrases that make a reel read as a promise rather
     than a lesson. A non-empty list is what the hype filter fires on.
--------------------------------------------------------------------------- */

interface ReelSeed {
  id: string;
  title: string;
  handle: string;
  name: string;
  hue: number;
  verified?: boolean;
  durationSec: number;
  caption: string;
  transcript: string;
  hashtags: string[];
  category: Category;
  topics: string[];
  difficulty: Difficulty;
  lane: ReelLane;
  genre: Genre;
  substance: number;
  hypeMarkers?: string[];
  outcome?: string;
  prerequisites?: string[];
  poster: [number, number, number];
  likes: number;
  saves: number;
  plays: number;
  daysAgo: number;
}

function build(seed: ReelSeed): Reel {
  const published = new Date(Date.now() - seed.daysAgo * 86_400_000).toISOString();
  return {
    id: seed.id,
    title: seed.title,
    creator: { handle: seed.handle, name: seed.name, hue: seed.hue, verified: seed.verified },
    durationSec: seed.durationSec,
    caption: seed.caption,
    transcript: seed.transcript,
    hashtags: seed.hashtags,
    category: seed.category,
    topics: seed.topics,
    difficulty: seed.difficulty,
    lane: seed.lane,
    genre: seed.genre,
    substance: seed.substance,
    hypeMarkers: seed.hypeMarkers ?? [],
    outcome: seed.outcome ?? "",
    prerequisites: seed.prerequisites ?? [],
    media: { poster: { from: seed.poster[0], to: seed.poster[1], angle: seed.poster[2] } },
    stats: { likes: seed.likes, saves: seed.saves, plays: seed.plays },
    publishedAt: published,
  };
}

